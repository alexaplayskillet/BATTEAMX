const parametros = new URLSearchParams(window.location.search);

const equipoSeleccionado = parametros.get("equipo");

const equipo = equipos[equipoSeleccionado];



if (equipo) {

    document.title = equipo.nombre + " - BatteaMX";

    document.getElementById("nombreEquipo").textContent =
        equipo.nombre;

    document.getElementById("descripcionEquipo").textContent =
        equipo.descripcion;

    document.getElementById("fundacion").textContent =
        equipo.fundacion;

    document.getElementById("ciudad").textContent =
        equipo.ciudad;

    document.getElementById("estadio").textContent =
        equipo.estadio;


    document.getElementById("logoEquipo").src =
        equipo.logo;


    document.getElementById("historia1").textContent =
        equipo.historia[0];

    document.getElementById("historia2").textContent =
        equipo.historia[1];

    document.getElementById("historia3").textContent =
        equipo.historia[2];


    document.getElementById("imagenPrincipal").src =
        equipo.imagenPrincipal;


    document.getElementById("galeria1").src =
        equipo.galeria[0];

    document.getElementById("galeria2").src =
        equipo.galeria[1];

    document.getElementById("galeria3").src =
        equipo.galeria[2];


    const timeline =
        document.getElementById("timeline");


    equipo.momentos.forEach(function(momento) {

        const elemento = document.createElement("div");

        elemento.classList.add("timeline-item");

        elemento.innerHTML = `
            <div class="timeline-punto"></div>

            <span class="timeline-anio">
                ${momento.anio}
            </span>

            <h3>
                ${momento.titulo}
            </h3>

            <p>
                ${momento.texto}
            </p>
        `;

        timeline.appendChild(elemento);

    });

} else {

    window.location.href = "index.html";

}